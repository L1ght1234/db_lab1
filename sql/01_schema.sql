DROP SCHEMA IF EXISTS public CASCADE;
CREATE SCHEMA public;


CREATE TYPE tournament_status AS ENUM ('draft', 'registration', 'ongoing', 'completed', 'cancelled');
CREATE TYPE match_status      AS ENUM ('scheduled', 'in_progress', 'completed', 'cancelled', 'postponed');
CREATE TYPE ticket_status     AS ENUM ('reserved', 'paid', 'cancelled', 'refunded');
CREATE TYPE match_event_type  AS ENUM ('goal', 'own_goal', 'penalty', 'point', 'foul',
                                       'yellow_card', 'red_card', 'substitution',
                                       'injury', 'timeout', 'other');
CREATE TYPE audit_operation   AS ENUM ('INSERT', 'UPDATE', 'DELETE', 'SOFT_DELETE', 'RESTORE');

CREATE TABLE roles (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(50) NOT NULL UNIQUE,
    description text
);
COMMENT ON TABLE roles IS 'Ролі користувачів (адміністратор, організатор, суддя, гравець, глядач)';

CREATE TABLE users (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id       integer      NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    email         varchar(255) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    first_name    varchar(100) NOT NULL,
    last_name     varchar(100) NOT NULL,
    phone         varchar(30),
    created_at    timestamptz  NOT NULL DEFAULT now(),
    created_by    integer      REFERENCES users(id) ON DELETE SET NULL,
    updated_at    timestamptz,
    updated_by    integer      REFERENCES users(id) ON DELETE SET NULL,
    is_deleted    boolean      NOT NULL DEFAULT false,
    deleted_at    timestamptz,
    deleted_by    integer      REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_users_soft_delete CHECK (is_deleted = (deleted_at IS NOT NULL))
);
COMMENT ON TABLE users IS 'Користувачі системи: організатори, судді, гравці, покупці квитків';


CREATE TABLE sports (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      varchar(100) NOT NULL UNIQUE,
    type      varchar(50)  NOT NULL,
    rules_url text
);
COMMENT ON TABLE sports IS 'Види спорту (командні / індивідуальні)';

CREATE TABLE venues (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(150) NOT NULL,
    city       varchar(100) NOT NULL,
    address    varchar(255) NOT NULL,
    capacity   integer      NOT NULL CHECK (capacity > 0),
    created_at timestamptz  NOT NULL DEFAULT now(),
    created_by integer      REFERENCES users(id) ON DELETE SET NULL,
    updated_at timestamptz,
    updated_by integer      REFERENCES users(id) ON DELETE SET NULL,
    is_deleted boolean      NOT NULL DEFAULT false,
    deleted_at timestamptz,
    deleted_by integer      REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_venues_soft_delete CHECK (is_deleted = (deleted_at IS NOT NULL))
);
COMMENT ON TABLE venues IS 'Спортивні арени / стадіони';

CREATE TABLE ticket_categories (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id   integer       NOT NULL REFERENCES venues(id) ON DELETE CASCADE,
    name       varchar(50)   NOT NULL,
    base_price numeric(10,2) NOT NULL CHECK (base_price >= 0),
    CONSTRAINT uq_venue_ticket_category UNIQUE (venue_id, name)
);
COMMENT ON TABLE ticket_categories IS 'Категорії місць на арені (VIP, трибуна тощо) з базовою ціною';

CREATE TABLE sponsors (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           varchar(150) NOT NULL UNIQUE,
    contact_person varchar(100),
    contact_email  varchar(255),
    created_at     timestamptz  NOT NULL DEFAULT now(),
    is_deleted     boolean      NOT NULL DEFAULT false,
    deleted_at     timestamptz,
    deleted_by     integer      REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_sponsors_soft_delete CHECK (is_deleted = (deleted_at IS NOT NULL))
);
COMMENT ON TABLE sponsors IS 'Спонсори турнірів';

CREATE TABLE teams (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_id     integer      NOT NULL REFERENCES sports(id) ON DELETE RESTRICT,
    name         varchar(120) NOT NULL,
    city         varchar(100),
    founded_year integer      CHECK (founded_year BETWEEN 1800 AND 2100),
    created_at   timestamptz  NOT NULL DEFAULT now(),
    created_by   integer      REFERENCES users(id) ON DELETE SET NULL,
    updated_at   timestamptz,
    updated_by   integer      REFERENCES users(id) ON DELETE SET NULL,
    is_deleted   boolean      NOT NULL DEFAULT false,
    deleted_at   timestamptz,
    deleted_by   integer      REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_teams_soft_delete CHECK (is_deleted = (deleted_at IS NOT NULL))
);
COMMENT ON TABLE teams IS 'Команди';

CREATE TABLE team_members (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id        integer     NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
    user_id        integer     NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    jersey_number  integer     CHECK (jersey_number BETWEEN 0 AND 99),
    "position"     varchar(50),
    joined_at      date        NOT NULL DEFAULT CURRENT_DATE,
    contract_until date,
    CONSTRAINT chk_team_member_contract CHECK (contract_until IS NULL OR contract_until >= joined_at)
);
COMMENT ON TABLE team_members IS 'Склад команди: гравці з номером, позицією та терміном контракту';

CREATE TABLE tournaments (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_id   integer           NOT NULL REFERENCES sports(id) ON DELETE RESTRICT,
    name       varchar(150)      NOT NULL,
    season     varchar(20)       NOT NULL,
    start_date date              NOT NULL,
    end_date   date              NOT NULL,
    status     tournament_status NOT NULL DEFAULT 'draft',
    created_at timestamptz       NOT NULL DEFAULT now(),
    created_by integer           REFERENCES users(id) ON DELETE SET NULL,
    updated_at timestamptz,
    updated_by integer           REFERENCES users(id) ON DELETE SET NULL,
    is_deleted boolean           NOT NULL DEFAULT false,
    deleted_at timestamptz,
    deleted_by integer           REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_tournament_dates       CHECK (end_date >= start_date),
    CONSTRAINT chk_tournaments_soft_delete CHECK (is_deleted = (deleted_at IS NOT NULL))
);
COMMENT ON TABLE tournaments IS 'Турніри (чемпіонати, кубки) за сезонами';

CREATE TABLE tournament_stages (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id integer      NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    name          varchar(100) NOT NULL,
    stage_order   integer      NOT NULL CHECK (stage_order > 0),
    CONSTRAINT uq_tournament_stage_order UNIQUE (tournament_id, stage_order)
);
COMMENT ON TABLE tournament_stages IS 'Етапи турніру (груповий етап, 1/4, фінал) у порядку проведення';

CREATE TABLE tournament_teams (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id integer     NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    team_id       integer     NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    registered_at timestamptz NOT NULL DEFAULT now(),
    seed_number   integer     CHECK (seed_number > 0),
    CONSTRAINT uq_tournament_team UNIQUE (tournament_id, team_id)
);
COMMENT ON TABLE tournament_teams IS 'Реєстрація команд у турнірі (N:M) з посівом';

CREATE TABLE tournament_sponsors (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id   integer       NOT NULL REFERENCES tournaments(id) ON DELETE CASCADE,
    sponsor_id      integer       NOT NULL REFERENCES sponsors(id) ON DELETE RESTRICT,
    contract_amount numeric(12,2) NOT NULL CHECK (contract_amount >= 0),
    signed_at       date          NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT uq_tournament_sponsor UNIQUE (tournament_id, sponsor_id)
);
COMMENT ON TABLE tournament_sponsors IS 'Спонсорські контракти турніру (N:M) із сумою';

CREATE TABLE matches (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id     integer      NOT NULL REFERENCES tournament_stages(id) ON DELETE RESTRICT,
    venue_id     integer      NOT NULL REFERENCES venues(id) ON DELETE RESTRICT,
    home_team_id integer      NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    away_team_id integer      NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    scheduled_at timestamptz  NOT NULL,
    status       match_status NOT NULL DEFAULT 'scheduled',
    created_at   timestamptz  NOT NULL DEFAULT now(),
    created_by   integer      REFERENCES users(id) ON DELETE SET NULL,
    updated_at   timestamptz,
    updated_by   integer      REFERENCES users(id) ON DELETE SET NULL,
    is_deleted   boolean      NOT NULL DEFAULT false,
    deleted_at   timestamptz,
    deleted_by   integer      REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT chk_different_teams      CHECK (home_team_id <> away_team_id),
    CONSTRAINT chk_matches_soft_delete  CHECK (is_deleted = (deleted_at IS NOT NULL))
);
COMMENT ON TABLE matches IS 'Матчі етапу турніру між двома командами на арені';

CREATE TABLE match_results (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id       integer NOT NULL UNIQUE REFERENCES matches(id) ON DELETE CASCADE,
    home_score     integer NOT NULL DEFAULT 0 CHECK (home_score >= 0),
    away_score     integer NOT NULL DEFAULT 0 CHECK (away_score >= 0),
    winner_team_id integer REFERENCES teams(id) ON DELETE RESTRICT,
    is_extra_time  boolean NOT NULL DEFAULT false,
    is_penalties   boolean NOT NULL DEFAULT false,
    notes          text
);
COMMENT ON TABLE match_results IS 'Результат матчу (1:1 з matches); NULL у winner_team_id - нічия';

CREATE TABLE match_events (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id      integer          NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    player_id     integer          REFERENCES users(id) ON DELETE SET NULL,
    event_type    match_event_type NOT NULL,
    minute        integer          NOT NULL CHECK (minute >= 0),
    details_jsonb jsonb
);
COMMENT ON TABLE match_events IS 'Події матчу (голи, картки, заміни); довільні деталі в JSONB';

CREATE TABLE match_officials (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id  integer     NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    user_id   integer     NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    duty_role varchar(50) NOT NULL,
    CONSTRAINT uq_match_official UNIQUE (match_id, user_id)
);
COMMENT ON TABLE match_officials IS 'Судді та офіційні особи, призначені на матч';


CREATE TABLE tickets (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id      integer       NOT NULL REFERENCES matches(id) ON DELETE RESTRICT,
    category_id   integer       NOT NULL REFERENCES ticket_categories(id) ON DELETE RESTRICT,
    buyer_user_id integer       NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    seat_number   varchar(30)   NOT NULL,
    price_paid    numeric(10,2) NOT NULL CHECK (price_paid >= 0),
    status        ticket_status NOT NULL DEFAULT 'reserved',
    purchased_at  timestamptz   NOT NULL DEFAULT now(),
    updated_at    timestamptz,
    updated_by    integer       REFERENCES users(id) ON DELETE SET NULL,
    is_deleted    boolean       NOT NULL DEFAULT false,
    deleted_at    timestamptz,
    deleted_by    integer       REFERENCES users(id) ON DELETE SET NULL,

    CONSTRAINT chk_tickets_soft_delete  CHECK (is_deleted = (deleted_at IS NOT NULL))
);
COMMENT ON TABLE tickets IS 'Квитки на матч: місце, категорія, покупець, статус оплати';

CREATE TABLE audit_log (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name varchar(63)     NOT NULL,
    record_id  integer         NOT NULL,
    operation  audit_operation NOT NULL,
    old_data   jsonb,
    new_data   jsonb,
    changed_by integer         REFERENCES users(id) ON DELETE SET NULL,
    changed_at timestamptz     NOT NULL DEFAULT now()
);
COMMENT ON TABLE audit_log IS 'Журнал змін: хто, коли і що змінив (старі та нові значення в JSONB). '
                              'На інші таблиці посилається за назвою та id, без зовнішнього ключа';
